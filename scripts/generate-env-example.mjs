#!/usr/bin/env node
/**
 * Scans the codebase for every `process.env.VAR_NAME` reference and
 * generates `.env.example` from the result (#1712).
 *
 * `lib/env.ts` had drifted from what the app actually reads, with no
 * canonical reference for a new contributor. This script IS that reference:
 * run it directly to (re)write `.env.example`, or run it with `--check` (as
 * CI does) to fail when `.env.example` no longer matches the codebase,
 * instead of letting the two silently drift apart again.
 *
 * Only plain `process.env.VAR_NAME` dot-access is scanned (the only pattern
 * used anywhere in this codebase at the time this script was written — no
 * `process.env["VAR"]` or destructured `const { VAR } = process.env` usage
 * exists). If such a pattern is introduced later, extend the regexes below.
 */
import { readFileSync, readdirSync, statSync, writeFileSync, existsSync } from "fs";
import { join, relative, dirname } from "path";
import { fileURLToPath } from "url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const SCAN_EXTENSIONS = new Set([".ts", ".tsx", ".js", ".jsx", ".mjs", ".cjs"]);
const IGNORE_DIRS = new Set([
  "node_modules",
  ".next",
  ".git",
  "coverage",
  "out",
  "dist",
  "test-results",
  "playwright-report",
]);
const ENV_VAR_PATTERN = /process\.env\.([A-Z_][A-Z0-9_]*)/g;
const OUTPUT_PATH = join(ROOT, ".env.example");
// This script's own docstring mentions the `process.env.X` pattern by
// example; exclude it from the scan so those examples aren't mistaken for
// real variables.
const SELF_PATH = fileURLToPath(import.meta.url);

function walk(dir, files = []) {
  for (const entry of readdirSync(dir)) {
    if (IGNORE_DIRS.has(entry)) continue;
    const full = join(dir, entry);
    const stat = statSync(full);
    if (stat.isDirectory()) {
      walk(full, files);
    } else if (SCAN_EXTENSIONS.has(entry.slice(entry.lastIndexOf(".")))) {
      files.push(full);
    }
  }
  return files;
}

function collectEnvVarNames() {
  const names = new Set();
  for (const file of walk(ROOT)) {
    if (file === SELF_PATH) continue;
    const contents = readFileSync(file, "utf8");
    for (const match of contents.matchAll(ENV_VAR_PATTERN)) {
      names.add(match[1]);
    }
  }
  return [...names].sort();
}

function renderEnvExample(names) {
  const header = [
    "# Auto-generated by `node scripts/generate-env-example.mjs` (#1712).",
    "# Do not edit by hand — run the script instead, or CI's --check step will",
    "# fail the next time a new `process.env.X` reference is added without",
    "# regenerating this file.",
    "#",
    "# Every variable below is read somewhere in the codebase. Set only the",
    "# ones your local setup actually needs; most integrations are optional",
    "# and validate themselves when enabled (see lib/env.ts).",
    "",
  ];
  const lines = names.map((name) => `${name}=`);
  return [...header, ...lines, ""].join("\n");
}

function main() {
  const names = collectEnvVarNames();
  const rendered = renderEnvExample(names);
  const checkOnly = process.argv.includes("--check");

  if (checkOnly) {
    const existing = existsSync(OUTPUT_PATH) ? readFileSync(OUTPUT_PATH, "utf8") : null;
    if (existing !== rendered) {
      console.error(
        "[generate-env-example] .env.example is out of date with the codebase's " +
          "process.env usage. Run `node scripts/generate-env-example.mjs` and commit the result."
      );
      process.exit(1);
    }
    console.log(`[generate-env-example] .env.example is current (${names.length} variables).`);
    return;
  }

  writeFileSync(OUTPUT_PATH, rendered);
  console.log(
    `[generate-env-example] wrote ${relative(ROOT, OUTPUT_PATH)} with ${names.length} variables.`
  );
}

main();
